#!/usr/bin/env python3
"""005 T019 — 사진을 넣은 기기 내 AI 측정 APK를 만든다(원격 실기기용, 예: Samsung Remote Test Lab).

사용: python3 tool/qa/build_ai_measure_apk.py <사진 폴더(*.jpg)> [--wait-min 15]
결과: build/app/outputs/flutter-apk/app-profile.apk

사진과 진입점은 build/ai_measure/(git 제외)에 생성한다. 사진 저작권 때문에 저장소에는 넣지 않는다.
"""
import argparse
import base64
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parents[2]


def dart_string(value: str) -> str:
    """Dart 작은따옴표 문자열 리터럴로 바꾼다. 파일명의 `'`·`$`·`\\`·줄바꿈을 이스케이프한다."""
    escaped = (
        value.replace("\\", "\\\\")
        .replace("'", "\\'")
        .replace("$", "\\$")
        .replace("\n", "\\n")
        .replace("\r", "\\r")
    )
    return f"'{escaped}'"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("photos", type=pathlib.Path)
    ap.add_argument("--wait-min", type=int, default=15, help="Gemini Nano model wait (minutes)")
    args = ap.parse_args()

    photos = sorted(args.photos.glob("*.jpg"))
    if not photos:
        print(f"No *.jpg in {args.photos}", file=sys.stderr)
        return 1

    out = ROOT / "build" / "ai_measure"
    out.mkdir(parents=True, exist_ok=True)
    entries = "\n".join(
        f"  {dart_string(p.name)}: {dart_string(base64.b64encode(p.read_bytes()).decode())},"
        for p in photos
    )
    (out / "photos.g.dart").write_text(
        "// Generated by tool/qa/build_ai_measure_apk.py. Do not commit.\n"
        f"const measurePhotos = <String, String>{{\n{entries}\n}};\n",
        encoding="utf-8",
    )
    (out / "main.dart").write_text(
        f"""// Generated by tool/qa/build_ai_measure_apk.py. Do not commit.
import 'dart:convert';
import 'dart:io';

import '../../integration_test/on_device_ai_measure.dart';
import 'photos.g.dart';

void main() => measureMain(() async {{
      final dir = await Directory.systemTemp.createTemp('measure_in');
      return [
        for (final e in measurePhotos.entries)
          File('${{dir.path}}/${{e.key}}')..writeAsBytesSync(base64Decode(e.value)),
      ];
    }}, aiWait: const Duration(minutes: {args.wait_min}));
""",
        encoding="utf-8",
    )
    print(f"Embedded {len(photos)} photos ({sum(p.stat().st_size for p in photos) // 1024} KB)")
    return subprocess.call(
        ["flutter", "build", "apk", "--profile", "--target-platform", "android-arm64",
         "-t", "build/ai_measure/main.dart"],
        cwd=ROOT,
    )


if __name__ == "__main__":
    sys.exit(main())
